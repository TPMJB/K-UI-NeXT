/* The split capture/completion uses only discovered driver/layout roles.
 * This removes its exact Evolution 1 identity gates and nothing else. */
#ifndef KUI_NATIVE_SPLIT_CONTROLLER_GENERAL
#define KUI_NATIVE_SPLIT_CONTROLLER_GENERAL 0
#endif
/* A separately linked persistent A2 service with synchronous disc I/O.
 * Its allocation contains only the worker, including its private stack. */
#ifndef KUI_NATIVE_VMU_ONLY
#define KUI_NATIVE_VMU_ONLY 0
#endif
#if KUI_NATIVE_VMU_ONLY != 0 && KUI_NATIVE_VMU_ONLY != 1
#error "VMU-only selector must be exactly zero or one"
#endif
#ifdef KUI_NATIVE_VMU_ONLY_TRANSPORT
#if KUI_NATIVE_VMU_ONLY_TRANSPORT != 0 && KUI_NATIVE_VMU_ONLY_TRANSPORT != 1
#error "VMU-only transport must be SCIF or SCI"
#endif
#define KUI_VMU_ONLY_TRANSPORT_STRING_(x) #x
#define KUI_VMU_ONLY_TRANSPORT_STRING(x) KUI_VMU_ONLY_TRANSPORT_STRING_(x)
#define KUI_VMU_ONLY_TRANSPORT_TEXT KUI_VMU_ONLY_TRANSPORT_STRING(KUI_NATIVE_VMU_ONLY_TRANSPORT)
#endif
/* VMU-lite: the same A2 service with bounded batch buffers. A2 owns one
 * receive slot per bank and the chain parser refuses a repeated slot, so a
 * batch stages at most one virtual reply; its chain copies hold 4 KiB. */
#ifndef KUI_NATIVE_VMU_LITE
#define KUI_NATIVE_VMU_LITE 0
#endif
#if KUI_NATIVE_VMU_LITE != 0 && KUI_NATIVE_VMU_LITE != 1
#error "VMU-lite selector must be exactly zero or one"
#endif
#if KUI_NATIVE_VMU_LITE && !KUI_NATIVE_VMU_ONLY
#error "VMU-lite refines the VMU-only service"
#endif
/* The general split controller with the controller prefetch TICK restored.
 * TICK was turned off only to isolate Evolution 1, which still failed
 * without it; the split controller then passed with TICK still off. */
#ifndef KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH
#define KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH 0
#endif
/* Restored split prefetch that pauses while the game streams heavily. */
#ifndef KUI_NATIVE_SPLIT_CONTROLLER_STREAM_GUARD
#define KUI_NATIVE_SPLIT_CONTROLLER_STREAM_GUARD 0
#endif
#if (KUI_NATIVE_READER_ONLY_ISOLATION != 0 && KUI_NATIVE_READER_ONLY_ISOLATION != 1) || \
    (KUI_NATIVE_STANDARD_VMU_ISOLATION != 0 && KUI_NATIVE_STANDARD_VMU_ISOLATION != 1) || \
    (KUI_NATIVE_RA_TICK_OFF_ISOLATION != 0 && KUI_NATIVE_RA_TICK_OFF_ISOLATION != 1) || \
    (KUI_NATIVE_E1_WAIT_CAPTURE != 0 && KUI_NATIVE_E1_WAIT_CAPTURE != 1) || \
    (KUI_NATIVE_MAPLE_BYPASS_ISOLATION != 0 && KUI_NATIVE_MAPLE_BYPASS_ISOLATION != 1) || \
    (KUI_NATIVE_MAPLE_DELAY_ISOLATION != 0 && KUI_NATIVE_MAPLE_DELAY_ISOLATION != 1) || \
    (KUI_NATIVE_MAPLE_DELAY_COMPLETE_ONLY_ISOLATION != 0 && KUI_NATIVE_MAPLE_DELAY_COMPLETE_ONLY_ISOLATION != 1) || \
    (KUI_NATIVE_MAPLE_DELAY_SUBMIT_ONLY_ISOLATION != 0 && KUI_NATIVE_MAPLE_DELAY_SUBMIT_ONLY_ISOLATION != 1) || \
    (KUI_NATIVE_MAPLE_DELAY_POST_START_ISOLATION != 0 && KUI_NATIVE_MAPLE_DELAY_POST_START_ISOLATION != 1) || \
    (KUI_NATIVE_METADATA_CACHE_ISOLATION != 0 && KUI_NATIVE_METADATA_CACHE_ISOLATION != 1) || \
    (KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION != 0 && KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION != 1) || \
    (KUI_NATIVE_SPLIT_CONTROLLER_GENERAL != 0 && KUI_NATIVE_SPLIT_CONTROLLER_GENERAL != 1) || \
    (KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH != 0 && KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH != 1) || \
    (KUI_NATIVE_SPLIT_CONTROLLER_STREAM_GUARD != 0 && KUI_NATIVE_SPLIT_CONTROLLER_STREAM_GUARD != 1)
#error "Native isolation selectors must be exactly zero or one"
#endif
#if KUI_NATIVE_SPLIT_CONTROLLER_GENERAL && !KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION
#error "General split controller extends the split controller build"
#endif
#if KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH && \
    (!KUI_NATIVE_SPLIT_CONTROLLER_GENERAL || KUI_NATIVE_RA_TICK_OFF_ISOLATION || \
     !KUI_NATIVE_READAHEAD || !KUI_NATIVE_COOP_PUMP)
#error "Split prefetch restores TICK on the general split controller's read-ahead build"
#endif
#if KUI_NATIVE_SPLIT_CONTROLLER_STREAM_GUARD && !KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH
#error "The stream guard pauses the restored split prefetch"
#endif
#if KUI_NATIVE_READER_ONLY_ISOLATION && KUI_NATIVE_STANDARD_VMU_ISOLATION
#error "Select one native isolation variant"
#endif
#if KUI_NATIVE_RA_TICK_OFF_ISOLATION && \
    ((!KUI_NATIVE_READER_ONLY_ISOLATION && !KUI_NATIVE_METADATA_CACHE_ISOLATION && \
      !KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION) || !KUI_NATIVE_DUAL_READERS)
#error "TICK-off isolation requires an explicit dual-reader control"
#endif
#if KUI_NATIVE_METADATA_CACHE_ISOLATION && \
    (!KUI_NATIVE_RA_TICK_OFF_ISOLATION || !KUI_NATIVE_DUAL_READERS || \
     !KUI_VMU_NATIVE_CACHED_CODE || !KUI_VMU_NATIVE_PERSISTENT_PROBE || \
     KUI_NATIVE_READER_ONLY_ISOLATION || KUI_NATIVE_STANDARD_VMU_ISOLATION || \
     KUI_NATIVE_MAPLE_BYPASS_ISOLATION || KUI_NATIVE_MAPLE_DELAY_ISOLATION || KUI_NATIVE_E1_WAIT_CAPTURE || \
     KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION)
#error "Metadata cache isolation requires cached persistent dual readers, TICK off, real callbacks and VMU"
#endif
#if KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION && \
    ((((!KUI_NATIVE_RA_TICK_OFF_ISOLATION && !KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH) || !KUI_NATIVE_DUAL_READERS) && !KUI_NATIVE_VMU_ONLY) || \
     !KUI_VMU_NATIVE_CACHED_CODE || !KUI_VMU_NATIVE_PERSISTENT_PROBE || \
     KUI_NATIVE_READER_ONLY_ISOLATION || KUI_NATIVE_STANDARD_VMU_ISOLATION || \
     KUI_NATIVE_MAPLE_BYPASS_ISOLATION || KUI_NATIVE_MAPLE_DELAY_ISOLATION || \
     KUI_NATIVE_E1_WAIT_CAPTURE || KUI_NATIVE_METADATA_CACHE_ISOLATION)
#error "Split controller isolation requires cached persistent dual readers, TICK off, real callbacks and VMU"
#endif
#if KUI_NATIVE_VMU_ONLY && \
    (!KUI_NATIVE_SPLIT_CONTROLLER_ISOLATION || !KUI_NATIVE_SPLIT_CONTROLLER_GENERAL || \
     !KUI_NATIVE_GENERAL_LEAN_LAYOUT || !KUI_VMU_NATIVE_PERSISTENT_PROBE || \
     !KUI_VMU_NATIVE_CACHED_CODE || KUI_NATIVE_DUAL_READERS || KUI_NATIVE_READAHEAD || \
     KUI_VMU_NATIVE_BACKGROUND || KUI_NATIVE_STANDARD_VMU_ISOLATION || \
     KUI_NATIVE_SPLIT_CONTROLLER_PREFETCH || KUI_NATIVE_RA_TICK_OFF_ISOLATION)
#error "VMU-only requires the compact persistent split worker and synchronous reader"
#endif
#if KUI_NATIVE_E1_WAIT_CAPTURE && \
    (!KUI_NATIVE_RA_TICK_OFF_ISOLATION || !KUI_NATIVE_READER_ONLY_ISOLATION || !KUI_NATIVE_DUAL_READERS)
#error "Evolution wait capture requires the reader-only TICK-off dual variant"
#endif
#if KUI_NATIVE_MAPLE_BYPASS_ISOLATION && \
    (!KUI_NATIVE_RA_TICK_OFF_ISOLATION || !KUI_NATIVE_READER_ONLY_ISOLATION || \
     !KUI_NATIVE_DUAL_READERS || KUI_NATIVE_E1_WAIT_CAPTURE)
#error "Maple bypass requires reader-only TICK-off isolation without wait capture"
#endif
#if KUI_NATIVE_MAPLE_DELAY_ISOLATION && \
    (!KUI_NATIVE_MAPLE_BYPASS_ISOLATION || !KUI_NATIVE_RA_TICK_OFF_ISOLATION || \
     !KUI_NATIVE_READER_ONLY_ISOLATION || !KUI_NATIVE_DUAL_READERS || KUI_NATIVE_E1_WAIT_CAPTURE)
#error "Maple delay requires the reader-only TICK-off Maple bypass without wait capture"
#endif
#if KUI_NATIVE_MAPLE_DELAY_COMPLETE_ONLY_ISOLATION && \
    (!KUI_NATIVE_MAPLE_DELAY_ISOLATION || !KUI_NATIVE_MAPLE_BYPASS_ISOLATION || \
     !KUI_NATIVE_READER_ONLY_ISOLATION || !KUI_NATIVE_RA_TICK_OFF_ISOLATION || \
     !KUI_NATIVE_DUAL_READERS || !KUI_VMU_NATIVE_PERSISTENT_PROBE || \
     KUI_NATIVE_E1_WAIT_CAPTURE || KUI_NATIVE_METADATA_CACHE_ISOLATION)
#error "Completion-only delay requires the persistent reader-only TICK-off Maple delay bypass"
#endif
#if KUI_NATIVE_MAPLE_DELAY_SUBMIT_ONLY_ISOLATION && \
    (!KUI_NATIVE_MAPLE_DELAY_ISOLATION || !KUI_NATIVE_MAPLE_BYPASS_ISOLATION || \
     !KUI_NATIVE_READER_ONLY_ISOLATION || !KUI_NATIVE_RA_TICK_OFF_ISOLATION || \
     !KUI_NATIVE_DUAL_READERS || !KUI_VMU_NATIVE_PERSISTENT_PROBE || \
     KUI_NATIVE_E1_WAIT_CAPTURE || KUI_NATIVE_METADATA_CACHE_ISOLATION)
#error "Submit-only delay requires the persistent reader-only TICK-off Maple delay bypass"
#endif
#if KUI_NATIVE_MAPLE_DELAY_COMPLETE_ONLY_ISOLATION && KUI_NATIVE_MAPLE_DELAY_SUBMIT_ONLY_ISOLATION
#error "Select one Maple delay phase"
#endif
#if KUI_NATIVE_MAPLE_DELAY_POST_START_ISOLATION && \
    (!KUI_NATIVE_MAPLE_DELAY_SUBMIT_ONLY_ISOLATION || !KUI_NATIVE_MAPLE_DELAY_ISOLATION || \
     !KUI_NATIVE_MAPLE_BYPASS_ISOLATION || !KUI_NATIVE_READER_ONLY_ISOLATION || \
     !KUI_NATIVE_RA_TICK_OFF_ISOLATION || !KUI_NATIVE_DUAL_READERS || \
     !KUI_VMU_NATIVE_PERSISTENT_PROBE || KUI_NATIVE_MAPLE_DELAY_COMPLETE_ONLY_ISOLATION || \
     KUI_NATIVE_E1_WAIT_CAPTURE || KUI_NATIVE_METADATA_CACHE_ISOLATION)
#error "Post-start delay requires the persistent reader-only TICK-off submit-only Maple delay bypass"
#endif
#if KUI_NATIVE_READER_ONLY_ISOLATION && !KUI_NATIVE_DUAL_READERS
#error "Reader-only isolation requires the current dual-reader build"
#endif
#if KUI_NATIVE_STANDARD_VMU_ISOLATION && \
    (KUI_NATIVE_DUAL_READERS || KUI_NATIVE_READAHEAD || KUI_VMU_NATIVE_BACKGROUND)
#error "Standard VMU isolation cannot enable a background reader"
#endif

