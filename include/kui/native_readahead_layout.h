#ifndef KUI_NATIVE_READAHEAD_LAYOUT_H
#define KUI_NATIVE_READAHEAD_LAYOUT_H
#include <stdint.h>
#ifndef KUI_NATIVE_READAHEAD
#define KUI_NATIVE_READAHEAD 0
#endif
#if KUI_NATIVE_READAHEAD != 0 && KUI_NATIVE_READAHEAD != 1
#error "KUI_NATIVE_READAHEAD must be zero or one"
#endif
#ifndef KUI_NATIVE_GENERAL_LEAN_LAYOUT
#define KUI_NATIVE_GENERAL_LEAN_LAYOUT 0
#endif
#if KUI_NATIVE_GENERAL_LEAN_LAYOUT != 0 && KUI_NATIVE_GENERAL_LEAN_LAYOUT != 1
#error "Native lean layout selector must be exactly zero or one"
#endif
#ifndef KUI_NATIVE_BACKGROUND_COMPACT
#define KUI_NATIVE_BACKGROUND_COMPACT 0
#endif
#if KUI_NATIVE_BACKGROUND_COMPACT != 0 && KUI_NATIVE_BACKGROUND_COMPACT != 1
#error "Compact Background selector must be exactly zero or one"
#endif
#if KUI_NATIVE_BACKGROUND_COMPACT && !KUI_NATIVE_GENERAL_LEAN_LAYOUT
#error "Compact Background extends the separately reviewed lean layout"
#endif
#if KUI_NATIVE_BACKGROUND_COMPACT
#define KUI_NATIVE_RA_LEASE_BYTES UINT32_C(0x47000)
#define KUI_NATIVE_RA_AUX_OFFSET UINT32_C(0x13000)
#define KUI_NATIVE_RA_STACK_OFFSET UINT32_C(0x16000)
#define KUI_NATIVE_RA_STACK_END UINT32_C(0x17000)
#define KUI_NATIVE_RA_DATA_OFFSET UINT32_C(0x17000)
#elif KUI_NATIVE_GENERAL_LEAN_LAYOUT
#define KUI_NATIVE_RA_LEASE_BYTES UINT32_C(0x51000)
#define KUI_NATIVE_RA_AUX_OFFSET UINT32_C(0x1d000)
#define KUI_NATIVE_RA_STACK_OFFSET UINT32_C(0x20000)
#define KUI_NATIVE_RA_STACK_END UINT32_C(0x21000)
#define KUI_NATIVE_RA_DATA_OFFSET UINT32_C(0x21000)
#else
#define KUI_NATIVE_RA_LEASE_BYTES UINT32_C(0x55000)
#define KUI_NATIVE_RA_AUX_OFFSET UINT32_C(0x21000)
#define KUI_NATIVE_RA_STACK_OFFSET UINT32_C(0x24000)
#define KUI_NATIVE_RA_STACK_END UINT32_C(0x25000)
#define KUI_NATIVE_RA_DATA_OFFSET UINT32_C(0x25000)
#endif
#define KUI_NATIVE_RA_AUX_SPAN UINT32_C(0x4000)
#define KUI_NATIVE_RA_AUX_IMAGE_BYTES UINT32_C(0x3000)
#define KUI_NATIVE_RA_DATA_BYTES UINT32_C(0x30000)
#define KUI_NATIVE_RA_BLOCKS 384u
#define KUI_NATIVE_RA_LOW_ENTRY_OFFSET 40u
#define KUI_NATIVE_RA_ENTRY_INDEX 0u
#define KUI_NATIVE_RA_CONTEXT_INDEX 1u
#define KUI_NATIVE_RA_OPS_MAGIC UINT32_C(0x4b52414f)
#define KUI_NATIVE_RA_AUX_MAGIC UINT32_C(0x4b524131)
#define KUI_NATIVE_RA_VERSION 1u
/* Keep the full 192 KiB cache directly after the auxiliary private stack.
 * Compaction removes unused gaps, never shared ownership or stack guards. */
_Static_assert(KUI_NATIVE_RA_AUX_OFFSET+KUI_NATIVE_RA_AUX_IMAGE_BYTES==KUI_NATIVE_RA_STACK_OFFSET,
    "Auxiliary initialized bytes stop before its private stack");
_Static_assert(KUI_NATIVE_RA_AUX_OFFSET+KUI_NATIVE_RA_AUX_SPAN==KUI_NATIVE_RA_STACK_END &&
    KUI_NATIVE_RA_STACK_END==KUI_NATIVE_RA_DATA_OFFSET,
    "Auxiliary stack and cache are adjacent disjoint spans");
_Static_assert(KUI_NATIVE_RA_DATA_OFFSET+KUI_NATIVE_RA_DATA_BYTES==KUI_NATIVE_RA_LEASE_BYTES,
    "The complete cache ends at the exact compact lease boundary");
#endif
