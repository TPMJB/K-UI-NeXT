#ifndef KUI_TOY_LOADER_IRQ_PROGRESS_H
#define KUI_TOY_LOADER_IRQ_PROGRESS_H

/* Shared by C and assembly. Values consumed by assembly have no C suffix. */
#ifndef KUI_TOY_PILOT_STARTUP_IRQ_PROFILE
#define KUI_TOY_PILOT_STARTUP_IRQ_PROFILE 0
#endif
#ifndef KUI_TOY_PILOT_DATA_TUNING_PROFILE
#define KUI_TOY_PILOT_DATA_TUNING_PROFILE 0
#endif
#ifndef KUI_TOY_PILOT_AD_FOLLOWUP_PROFILE
#define KUI_TOY_PILOT_AD_FOLLOWUP_PROFILE 0
#endif
#ifndef KUI_TOY_PILOT_DATA_BUDGET_PROFILE
#define KUI_TOY_PILOT_DATA_BUDGET_PROFILE 0
#endif
#ifndef KUI_TOY_PILOT_DATA_SCHEDULE_MODE
#define KUI_TOY_PILOT_DATA_SCHEDULE_MODE 0
#endif
#if KUI_TOY_PILOT_STARTUP_IRQ_PROFILE < 0 || KUI_TOY_PILOT_STARTUP_IRQ_PROFILE > 2
#error Toy startup IRQ profile must be 0, 1 or 2
#endif
#if KUI_TOY_PILOT_STARTUP_IRQ_PROFILE && \
    (KUI_TOY_PILOT_DATA_TUNING_PROFILE != 1 || \
     KUI_TOY_PILOT_AD_FOLLOWUP_PROFILE != 2 || \
     KUI_TOY_PILOT_DATA_BUDGET_PROFILE != 4 || \
     KUI_TOY_PILOT_DATA_SCHEDULE_MODE != 2 || \
     !KUI_TOY_PILOT_PRIVATE_P2 || KUI_TOY_PILOT_NATIVE_CACHE || \
     KUI_TOY_PILOT_SHARED_SCI || KUI_TOY_PILOT_ASYNC_CDDA || \
     KUI_TOY_PILOT_SYNTHETIC_SOURCE || !KUI_TOY_PILOT_LOADER_TRACE || \
     !KUI_TOY_PILOT_DATA_PROBE || KUI_TOY_PILOT_DATA_PAYLOAD_MODE || \
     KUI_TOY_PILOT_GD_FIXED_STEP != 2 || KUI_SCI_DMA_REUSE_TDRE)
#error Startup IRQ experiments require the complete admitted AI configuration
#endif

#include "kui/toy_loader_data_pipeline.h"

#if KUI_TOY_PILOT_STARTUP_IRQ_PROFILE
#define KUI_TOY_STARTUP_SCI_NIBBLE 0x70
#define KUI_TOY_STARTUP_SCI_LEVEL 0x0070u
#define KUI_TOY_STARTUP_SCI_PRIORITY 7
#define KUI_TOY_IRQ_REPORT_PROFILE (12u + KUI_TOY_PILOT_STARTUP_IRQ_PROFILE)
#else
#define KUI_TOY_STARTUP_SCI_NIBBLE 0x10
#define KUI_TOY_STARTUP_SCI_LEVEL 0x0010u
#define KUI_TOY_STARTUP_SCI_PRIORITY 1
#endif

#endif
